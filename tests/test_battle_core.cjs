const assert=require('node:assert/strict'),b=require('./battle_core.js');
const p={attack:10000,attRate:1,pow:1,defence:2000,sourceElement:'Fire',targetElement:'Fire',criticalRate:.15,criticalDamageRate:1.3};
assert.equal(b.rawSkillDamage(p).value,9355);
assert.equal(b.rawSkillDamage({...p,penetrations:[.5,0,0]}).effectiveDefence,1000);
assert.equal(b.rawSkillDamage({...p,penetrations:[.5,.5,0]}).effectiveDefence,500);
assert.equal(b.rawSkillDamage({...p,penetrations:[.5,.5,0],antiPenetrate:1}).effectiveDefence,2000);
assert.equal(b.hitChances({...p,mustDodge:1,mustHit:1,mustCritical:1}).dodge,1);
assert.equal(b.hitChances({...p,mustCritical:1,noCritical:1}).critical,1);
assert.equal(b.hitChances({...p,mustBigHit:1,noBigHit:1,criticalRate:0}).big,1);
assert.equal(b.hitChances({...p,sourceElement:'Ice',targetElement:'Fire'}).raw.critical,Math.fround(.15+.15));
assert.equal(b.hitChances({...p,sourceElement:'Fire',targetElement:'Ice'}).raw.dodge,.5);
assert.equal(b.hitChances({...p,sourceElement:'Light',targetElement:'Dark'}).raw.dodge,0);
assert.ok(Math.abs(b.reduction({hurtReductions:[.1,.2,-.05,-.1]}).multiplier-.95)<1e-6);
assert.ok(Math.abs(b.reduction({hurtReductions:[.1,.2,-.05,-.1],ignoreHurtReduction:true}).multiplier-1.15)<1e-6);
assert.equal(b.settle({...p,shield:1000,invincible:true},1).remainingShield,1000);
assert.equal(b.settle({...p,currentHP:100,immortal:true},1).hpLoss,99);
assert.equal(b.settle({...p,currentHP:100},1).hpLoss,100);
assert.deepEqual([2.5,3.5,-2.5,-3.5].map(b.roundEven),[2,4,-2,-4]);
assert.equal(b.finalStat(100.5,0,0,0,'Attack'),100);
assert.equal(b.finalStat(100.5,0,0,0,'MaxHP'),100);
assert.equal(b.finalStat(101.5,0,0,0,'MaxHP'),102);
assert.ok(Math.abs(b.effectChance(.5,0,0)-.425)<1e-6);
assert.equal(b.effectChance(.5,0,2),0);
console.log('通过：基础伤害、三路穿透与抗穿透、判定优先级、克制、减伤分量、无敌/护盾、不死、伤害与面板舍入、状态概率。');
